/** Лёгкий стеммер для русского: срезает частотные окончания. */
function stem(word: string): string {
  if (word.length <= 4) return word;

  const suffixes = [
    "ированиями",
    "ированием",
    "ированию",
    "ирования",
    "ированные",
    "ями",
    "ами",
    "иями",
    "ов",
    "ев",
    "ой",
    "ый",
    "ий",
    "ая",
    "яя",
    "ое",
    "ее",
    "ые",
    "ие",
    "ому",
    "ему",
    "ых",
    "их",
    "ую",
    "юю",
    "ем",
    "ом",
    "ах",
    "ях",
    "ться",
    "тся",
    "ешь",
    "ишь",
    "ете",
    "ите",
    "ут",
    "ют",
    "ат",
    "ят",
    "ла",
    "ло",
    "ли",
    "ть",
    "ся",
    "а",
    "я",
    "о",
    "е",
    "у",
    "ю",
    "ы",
    "и",
    "ь",
  ];

  for (const suffix of suffixes) {
    if (word.length - suffix.length >= 4 && word.endsWith(suffix)) {
      return word.slice(0, word.length - suffix.length);
    }
  }
  return word;
}

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, "е");
}

/** Разбивает текст на нормализованные основы слов, пригодные для BM25. */
export function tokenize(text: string): string[] {
  const words = normalize(text).split(/[^a-zа-я0-9]+/).filter(Boolean);
  const tokens: string[] = [];
  for (const word of words) {
    if (STOPWORDS.has(word) || word.length < 2) continue;
    tokens.push(stem(word));
  }
  return tokens;
}

/** Токены запроса + токены синонимов/расшифровок аббревиатур. */
export function tokenizeQuery(query: string): string[] {
  const words = normalize(query).split(/[^a-zа-я0-9]+/).filter(Boolean);
  const expanded: string[] = [...words];
  for (const word of words) {
    const synonyms = SYNONYMS[word] ?? SYNONYMS[stem(word)];
    if (synonyms) expanded.push(...synonyms);
  }
  return tokenize(expanded.join(" "));
}

