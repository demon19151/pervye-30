/** Собирает нумерованный блок контекста; номера совпадают со ссылками [n] в ответе. */
export function buildContextBlock(chunks: RetrievedChunk[]): string {
  const toPlainText = (s: string) => {
    return s
      // markdown links: [text](url) -> text
      .replace(/\[([^\]]+)\]\(([^)]+)\)/g, "$1")
      // bold: **text** -> text
      .replace(/\*\*([^*]+)\*\*/g, "$1")
      // inline code: `code` -> code
      .replace(/`([^`]+)`/g, "$1");
  };

  const fragments = chunks.map((item) => {
    const { chunk } = item;
    const header = [
      chunk.title,
      chunk.heading && chunk.heading !== chunk.title ? `раздел: ${chunk.heading}` : null,
      chunk.source ? `источник: ${chunk.source}` : null,
    ]
      .filter(Boolean)
      .join(" · ");
    return `${header}\n${toPlainText(chunk.text)}`;
  });

  return `КОНТЕКСТ (фрагменты базы знаний ИРИТ-РТФ / УрФУ):\n\n${fragments.join("\n\n---\n\n")}`;
}

/** Дополняет короткий уточняющий вопрос предыдущим. Новую тему не склеивает. */
export function buildSearchQuery(question: string, previousQuestions: string[]): string {
  if (previousQuestions.length === 0) return question;

  const previous = previousQuestions[previousQuestions.length - 1];
  const words = question.trim().split(/\s+/).filter(Boolean);
  const looksLikeFollowUp = words.length <= 6 || /^(а|и)\b/i.test(question.trim());
  if (!looksLikeFollowUp) return question;

  const currentTokens = tokenizeQuery(question);
  const previousTokens = new Set(tokenizeQuery(previous));
  if (currentTokens.length <= 1) return `${previous} ${question}`;

  const overlap = currentTokens.filter((token) => previousTokens.has(token)).length;
  if (overlap / currentTokens.length < 0.34) return question;

  return `${previous} ${question}`;
}

